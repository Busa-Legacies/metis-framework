def heal_task_counter(apply):
    """#1607: auto-heal the task-id counter regression (reconcile I6) instead of leaving it
    detect-only. Invariant: task-counter.json `lastAssigned` must be >= the max task id in
    tasks.json (active + archived tombstones), or the next create-task mints a colliding id
    (the 2026-07-31 fleet incident). The merge=taskstate driver now maxes the counter against
    tasks.json on every merge (#1601), but a collision-renumber in _merge_tasks can still mint
    max+1 that the pre-merge read misses — so a Layer-A bump closes that residual tail. Bumping
    the counter UP to the max id is mechanical, safe and strictly forward (an id is never
    re-issued, no work is touched), which is exactly the auto-heal class, unlike the
    judgment-laden lease/task-state invariants that stay detect-only."""
    cpath = os.path.join(REPO, "docs/process/state/task-counter.json")
    tpath = os.path.join(REPO, "docs/process/state/tasks.json")
    try:
        with open(cpath, encoding="utf-8") as f:
            counter = json.load(f)
        with open(tpath, encoding="utf-8") as f:
            tasks_doc = json.load(f)
    except (OSError, ValueError) as e:
        return {"name": "task-counter", "status": NEEDS_HUMAN,
                "detail": f"task-counter/tasks.json unreadable: {e}", "actions": []}
    last = counter.get("lastAssigned", 0)
    ids = []
    for t in tasks_doc.get("tasks", []) or []:
        m = re.fullmatch(r"#(\d+)", str((t or {}).get("taskId", "")))
        if m:
            ids.append(int(m.group(1)))
    for a in tasks_doc.get("archivedIds", []) or []:
        m = re.fullmatch(r"#(\d+)", str(a))
        if m:
            ids.append(int(m.group(1)))
    max_id = max(ids, default=0)
    if last >= max_id:
        return {"name": "task-counter", "status": OK,
                "detail": f"counter healthy (lastAssigned {last} >= max id {max_id})", "actions": []}
    if not apply:
        return {"name": "task-counter", "status": NEEDS_HUMAN,
                "detail": f"counter regressed: lastAssigned {last} < max id {max_id} (reconcile I6)",
                "actions": [f"bump task-counter lastAssigned {last} -> {max_id} (re-run with --apply)"]}
    counter["lastAssigned"] = max_id
    counter["updatedAt"] = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    with open(cpath, "w", encoding="utf-8") as f:
        json.dump(counter, f, indent=2)
        f.write("\n")
    msg = (f"fix(I6): self-heal bump task-counter lastAssigned {last} -> {max_id} "
           f"(counter lagged the max task id; next mint would collide)")
    rc, out = sh(["bash", os.path.join(REPO, "scripts", "git-lock.sh"), "run",
                  "git", "commit", "-m", msg, "--", "docs/process/state/task-counter.json"], timeout=60)
    if rc != 0:
        return {"name": "task-counter", "status": NEEDS_HUMAN,
                "detail": f"bumped lastAssigned {last} -> {max_id} but commit failed (rc {rc})",
                "actions": [out.strip()[:160] or "git-lock commit failed"]}
    return {"name": "task-counter", "status": HEALED,
            "detail": f"bumped task-counter lastAssigned {last} -> {max_id} (I6 residual closed)",
            "actions": [msg]}


