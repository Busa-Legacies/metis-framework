def heal_drain_clone_sync_wedge(apply):
    """#5275: detect + safely recover the ff-only auto-sync wedge on a drain clone (a
    checkout a relay poller drains). Detect = behind origin/main AND ff-only would be
    refused (diverged local commits and/or dirty tracked files). Recover (apply mode) =
    isolate the WIP first — stash tracked dirt, branch local commits — then converge to
    origin (ff-merge when possible, reset --hard only after both preservation steps are
    verified), and page via discord-alert.sh with where the WIP now lives. Dry-run =
    REPORT the wedge + the recovery plan, touch nothing."""
    name = "drain-clone-sync-wedge"
    # Gate: only a drain/appliance clone — a machine running a relay poller, healing the
    # checkout that poller drains (the primary ~/metis-os, never a dev worktree).
    poller_installed = any(
        os.path.exists(os.path.join(HOME, "Library", "LaunchAgents", f"{l}.plist"))
        for l in ("ant.relay-poller", "<<MACHINE_2_USER>>.relay-poller"))
    is_primary_checkout = os.path.realpath(REPO) == os.path.realpath(os.path.join(HOME, "metis-os"))
    if not (poller_installed and is_primary_checkout):
        return {"name": name, "status": OK,
                "detail": "not a drain clone (no relay poller here, or not the primary checkout)",
                "actions": []}

    rc, _ = sh(["git", "fetch", "origin", "main", "--quiet"], timeout=90)
    if rc != 0:
        return {"name": name, "status": OK,
                "detail": "fetch origin failed (offline?) — freshness unverifiable this run; "
                          "the relay-clone-freshness loop contract escalates if this persists",
                "actions": []}
    rc, out = sh(["git", "rev-list", "--left-right", "--count", "HEAD...origin/main"])
    try:
        ahead, behind = (int(x) for x in out.split())
    except (ValueError, TypeError):
        return {"name": name, "status": NEEDS_HUMAN,
                "detail": f"could not compute behind/ahead vs origin/main ({out.strip()[:120]})",
                "actions": ["inspect the drain clone's git state by hand"]}
    rc, out = sh(["git", "status", "--porcelain"])
    dirty = [l for l in out.splitlines() if l.strip() and not l.startswith("??")] if rc == 0 else []

    if behind <= DRAIN_WEDGE_MAX_BEHIND:
        _drain_wedge_touch_ok(f"behind={behind} ahead={ahead} dirty={len(dirty)}")
        return {"name": name, "status": OK,
                "detail": f"drain clone current (behind {behind}/ahead {ahead})", "actions": []}
    if ahead == 0 and not dirty:
        # Behind but cleanly fast-forwardable — a normal sync gap, the auto-sync daemon's
        # next pull converges it. Not a wedge; don't race the daemon.
        _drain_wedge_touch_ok(f"behind={behind} but ff-able (ahead 0, clean)")
        return {"name": name, "status": OK,
                "detail": f"behind {behind} but fast-forwardable (clean tree, no local commits) "
                          "— auto-sync will converge", "actions": []}

    # Wedge SIGNATURE: behind AND ff-only refused (diverged and/or dirty tracked files). On the
    # primary drain clone this is the steady state of normal auto-sync churn, so it is NOT yet
    # actionable — only a wedge that PERSISTS past DRAIN_WEDGE_MIN_PERSIST_SEC (the daemon had
    # ample time to converge and did not) warrants the WIP-isolating recovery (#5275). A healthy
    # tick in between clears the counter, so transient churn never accrues enough age to act.
    host = os.uname().nodename.split(".")[0]
    wedge = (f"behind {behind} / ahead {ahead}, {len(dirty)} dirty tracked file(s) — "
             f"ff-only auto-sync is refused; the relay poller is draining a frozen view")
    age = _drain_wedge_note_pending(f"behind={behind} ahead={ahead} dirty={len(dirty)}")
    if age < DRAIN_WEDGE_MIN_PERSIST_SEC:
        return {"name": name, "status": OK,
                "detail": f"wedge signature seen ({wedge}) but not yet persistent "
                          f"({age // 60}m < {DRAIN_WEDGE_MIN_PERSIST_SEC // 60}m) — normal "
                          f"auto-sync churn self-converges; watching, no action taken",
                "actions": []}
    wedge = f"{wedge}; PERSISTED {age // 60}m"
    if not apply:
        return {"name": name, "status": NEEDS_HUMAN,
                "detail": f"WEDGED: {wedge}",
                "actions": ["apply-mode recovery: stash tracked dirt + branch local commits "
                            "(WIP isolated, nothing destroyed), then converge to origin/main",
                            "or recover by hand per reference_appliance_mirror_git_sync_reset_hard"]}

    ts = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    actions = []
    # Step 1 — isolate dirty tracked WIP into a stash (reversible; untracked files are left
    # alone — reset --hard preserves them anyway).
    if dirty:
        rc, out = sh(["git", "stash", "push", "-m", f"self-heal drain-wedge isolate {ts}"], timeout=120)
        rc2, out2 = sh(["git", "status", "--porcelain"])
        still_dirty = [l for l in out2.splitlines() if l.strip() and not l.startswith("??")] if rc2 == 0 else ["?"]
        if rc != 0 or still_dirty:
            _drain_wedge_alert(f"🔴 self-heal on {host}: drain clone WEDGED ({wedge}) and the "
                               f"WIP-isolating stash FAILED — NOT proceeding to any destructive "
                               f"step. Recover by hand.")
            return {"name": name, "status": NEEDS_HUMAN,
                    "detail": f"WEDGED ({wedge}); stash of dirty WIP failed — recovery halted "
                              "before any destructive step",
                    "actions": [f"git stash said: {out.strip()[:200]}", "recover by hand"]}
        actions.append(f"stashed {len(dirty)} dirty tracked file(s): 'self-heal drain-wedge isolate {ts}'")
    # Step 2 — preserve local commits on a branch before the checkout moves.
    branch = None
    if ahead > 0:
        branch = f"self-heal/drain-wip-{ts}"
        rc, out = sh(["git", "branch", branch, "HEAD"])
        rc2, _ = sh(["git", "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}"])
        if rc != 0 or rc2 != 0:
            _drain_wedge_alert(f"🔴 self-heal on {host}: drain clone WEDGED ({wedge}) and "
                               f"branching the {ahead} local commit(s) FAILED — NOT proceeding "
                               f"to reset. Recover by hand.")
            return {"name": name, "status": NEEDS_HUMAN,
                    "detail": f"WEDGED ({wedge}); could not branch the {ahead} local commit(s) — "
                              "recovery halted before any destructive step",
                    "actions": [f"git branch said: {out.strip()[:200]}", "recover by hand"]}
        actions.append(f"preserved {ahead} local commit(s) on branch {branch}")
    # Step 3 — converge. ff-merge when the history allows it; reset --hard ONLY now that the
    # WIP is verifiably isolated (stash confirmed empty-tree, commits confirmed on a branch).
    if ahead == 0:
        rc, out = sh(["git", "merge", "--ff-only", "origin/main"], timeout=120)
        actions.append("git merge --ff-only origin/main")
    else:
        rc, out = sh(["git", "reset", "--hard", "origin/main"], timeout=120)
        actions.append("git reset --hard origin/main (WIP already isolated above)")
    rc2, head = sh(["git", "rev-parse", "HEAD"])
    rc3, origin = sh(["git", "rev-parse", "origin/main"])
    converged = rc == 0 and rc2 == 0 and rc3 == 0 and head.strip() == origin.strip()
    wip_note = " · ".join(a for a in actions if "stashed" in a or "preserved" in a) or "no WIP to isolate"
    if not converged:
        _drain_wedge_alert(f"🔴 self-heal on {host}: drain clone WEDGED ({wedge}); WIP isolated "
                           f"({wip_note}) but the sync step FAILED ({out.strip()[:150]}). "
                           f"Hand recovery needed.")
