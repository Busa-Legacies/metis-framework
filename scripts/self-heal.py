# Interim guard for the memory re-architecture (#757). The harness loads MEMORY.md WHOLE
# each session at a hard ~24.4KB cap and SILENTLY TRUNCATES the overflow (lost memory).
MEMORY_INDEX = os.path.join(REPO, "ClaudeCode", "memory", "MEMORY.md")
MEMORY_MAINTAINER = os.path.join(REPO, "ClaudeCode", "scripts", "memory-maintain.py")
MEMORY_HARD_CAP = 24400   # past this the whole-file load is truncated → silent memory loss
MEMORY_SOFT_CAP = 22000   # act here, with margin, BEFORE the hard cap
_INDEX_ENTRY = re.compile(r'^- (?:\[[^\]]*\]\()?([^\s\)]+\.md)\)?')


def _memory_index_bytes():
    try:
        return os.path.getsize(MEMORY_INDEX)
    except OSError:
        return 0


def _stale_active_candidates(max_n=8, stale_days=45):
    """#active project/feedback index entries whose memory FILE hasn't been git-touched in
    > stale_days — the demote-to-cold candidates that would actually shed hot-index bytes.
    Detection only: whether a rule is still 'active' is a judgment call, never auto-demoted."""
    out = []
    try:
        lines = open(MEMORY_INDEX, encoding="utf-8").read().splitlines()
    except OSError:
        return out
    now = time.time()
    for line in lines:
        m = _INDEX_ENTRY.match(line)
        if not m or "#active" not in line:
            continue
        fname = m.group(1)
        if not (fname.startswith("project_") or fname.startswith("feedback_")):
            continue
        rc, ts = sh(["git", "-C", REPO, "log", "-1", "--format=%ct", "--",
                     os.path.join("ClaudeCode", "memory", fname)])
        try:
            age_days = (now - int((ts or "").strip())) / 86400
        except (ValueError, TypeError):
            continue
        if age_days > stale_days:
            out.append((age_days, f"{fname} ({int(age_days)}d untouched)"))
    out.sort(reverse=True)
    return [s for _, s in out[:max_n]]


def check_memory_index_pressure(apply):
    """Interim guard for the memory re-architecture (#757). Because #active decayed to
    'exists' (nothing drops it on closure) and the maintainer never auto-ran, the hot index
    ratcheted to the truncation cap unnoticed (2026-07-14: 24764B > 24400B = lost memory).
    Act at a SOFT cap with margin: in apply mode auto-run the maintainer (idempotent, and it
    only MOVES index lines hot<->cold — cold stays recall-reachable, never deleted, so it is
    safe/reversible → Layer-A); if re-partition isn't enough (because #active is over-applied)
    surface the stale #active demote-candidates so the next session can act. Root fix: #757."""
    b = _memory_index_bytes()
    if b == 0:
        return {"name": "memory-index-pressure", "status": NEEDS_HUMAN,
                "detail": f"cannot read {os.path.relpath(MEMORY_INDEX, REPO)}", "actions": []}
    if b < MEMORY_SOFT_CAP:
        return {"name": "memory-index-pressure", "status": OK,
                "detail": f"hot index {b}B < {MEMORY_SOFT_CAP}B soft cap", "actions": []}
    tried = False
    if apply and os.path.exists(MEMORY_MAINTAINER):
        sh([sys.executable, MEMORY_MAINTAINER, "--apply"], timeout=60)
        tried = True
        nb = _memory_index_bytes()
        if nb < MEMORY_SOFT_CAP:
            return {"name": "memory-index-pressure", "status": HEALED,
                    "detail": f"maintainer re-partitioned hot index {b}B → {nb}B (< soft cap)",
                    "actions": ["ran memory-maintain.py --apply (hot→cold re-partition)"]}
        b = nb  # escalate with the post-maintainer size
    over_hard = b >= MEMORY_HARD_CAP
    lead = f"hot index {b}B " + (">= HARD cap — TRUNCATING at load (lost memory)"
                                 if over_hard else f">= {MEMORY_SOFT_CAP}B soft cap")
    detail = lead + ("; maintainer re-partition insufficient (#active over-applied)"
                     if tried else "; run the maintainer + retire stale #active")
    actions = ["retire a closed #active entry (drop the tag), then: "
               "python3 ClaudeCode/scripts/memory-maintain.py --apply"]
    cands = _stale_active_candidates()
    if cands:
        actions.append("stale #active demote-candidates: " + "; ".join(cands))
    actions.append("root fix in progress: #757 memory re-architecture")
    return {"name": "memory-index-pressure", "status": NEEDS_HUMAN,
            "detail": detail, "actions": actions, "escalation": AGENT}


def heal_merge_drivers(apply):
    """Merge-driver registration guard + auto-heal (2026-07-09 recurring wedge). A file
    mapped to a custom merge=<driver> in .gitattributes whose driver is NOT registered in
    this clone's git config silently falls back to a raw 3-way merge -> conflict -> the
    auto-sync daemon dies mid-merge and wedges the whole clone (MEMORY.md/working-context.md
    hit this twice in one day; tasks.json #147; health-checks.json #437). Registration writes
    only .git/config and is fully idempotent, so daily --apply keeps EVERY machine self-healed
    — including a headless/unreachable one that can't be fixed by hand — via the versioned
    register-merge-drivers.sh (which picks up any driver added to .gitattributes later)."""
    ga = os.path.join(REPO, ".gitattributes")
    if not os.path.exists(ga):
        return {"name": "merge-drivers", "status": OK, "detail": "no .gitattributes", "actions": []}
    drivers = sorted({m.group(1) for m in
                      (re.search(r"\smerge=([A-Za-z0-9_-]+)", l) for l in open(ga)) if m}
                     - {"union"})   # union is a git built-in; needs no registration

    def _missing():
        return [d for d in drivers
                if sh(["git", "-C", REPO, "config", "--get", f"merge.{d}.driver"])[0] != 0]

    missing = _missing()
    if not missing:
        return {"name": "merge-drivers", "status": OK,
                "detail": f"{len(drivers)} .gitattributes driver(s) registered", "actions": []}
    if not apply:
        return {"name": "merge-drivers", "status": NEEDS_HUMAN,
                "detail": f"unregistered merge driver(s): {' '.join(missing)} — will wedge on a 3-way merge",
                "actions": ["run scripts/register-merge-drivers.sh"]}
    sh(["bash", os.path.join(REPO, "scripts", "register-merge-drivers.sh")])
    still = _missing()
    if not still:
        return {"name": "merge-drivers", "status": HEALED,
                "detail": f"registered {len(missing)} missing merge driver(s): {' '.join(missing)}",
                "actions": [f"registered {' '.join(missing)}"]}
    return {"name": "merge-drivers", "status": NEEDS_HUMAN,
            "detail": "register-merge-drivers.sh ran but drivers still missing",
            "actions": [f"still missing: {' '.join(still)}"]}


