# Snippet emitted to each origin (local or over ssh). Prints the node's EFFECTIVE
# served metis-command app identity. "effective" resolves the #2186 overlay: when the
# working-tree app dir equals origin/main (a clean ff-sync OR the remote-failover
# overlay), the node builds+serves origin's app -> key on origin/main's app-tree SHA;
# only when the tree diverges from origin is the node serving something else -> key on
# HEAD's app-tree SHA. So the overlay self-heal reads as parity, never a false drift.
#
# It ALSO reports `built` — the id of the bundle the node would actually serve
# (.next/BUILD_ID). Source identity alone was not enough (2026-08-19): an origin that
# slept through a deploy gets its redeploy QUEUED (#928 marker), then git-sync pulls it
# SOURCE-current when it wakes, so the git keys above read perfect parity while its
# frozen .next is whatever it last built. `next start` serves that stale bundle, the CF
# pool hands out its HTML, and the browser's follow-up GET for the chunk hashes that
# HTML names lands on an origin that never built them -> 404 -> the unstyled cockpit.
# next.config.ts pins generateBuildId to `git rev-parse origin/main:projects/metis-
# command` (full SHA) — the same tree `eff` names in short form — so `built` is directly
# comparable ACROSS origins, which is the comparison that matters.
#
# And `pending` — whether this node is holding a QUEUED failover redeploy it still owes
# its peer. That marker is the deploy's own record that the origins are knowingly out of
# sync; scripts/mc-origin-drain.sh clears it within ~5min of the peer waking, so a marker
# still standing at heal time means the drain itself is stuck and needs a human. The path
# is spelled out INLINE on purpose — this snippet is piped over ssh to a peer that may not
# carry any shared lib — so it must stay in sync with PENDING_MARK in
# deploy-metis-command.sh and mc-origin-drain.sh if that marker is ever renamed.
_MC_ID_SNIPPET = r'''
REPO="$HOME/metis-os"
cd "$REPO" 2>/dev/null || { echo "MCID none no-repo none none none 0"; exit 0; }
git fetch --quiet origin main 2>/dev/null || true
head_app=$(git rev-parse --short HEAD:projects/metis-command 2>/dev/null || echo '')
orig_app=$(git rev-parse --short origin/main:projects/metis-command 2>/dev/null || echo '')
if git diff --quiet origin/main -- projects/metis-command 2>/dev/null; then wt=origin; eff="$orig_app"; else wt=local; eff="$head_app"; fi
built=''; _bid=projects/metis-command/.next/BUILD_ID
[ -f "$_bid" ] && built=$(tr -d '[:space:]' < "$_bid" 2>/dev/null)
pending=0; [ -f "$HOME/.openclaw/metis-command/<<MACHINE_2_ID>>-redeploy-pending" ] && pending=1
echo "MCID ${eff:-none} ${wt} ${head_app:-none} ${orig_app:-none} ${built:-none} ${pending}"
'''

def _ssh_base():
    """ssh opts + every known fleet identity file that exists on this runner (ssh
    tries each; agent keys still work too). Fail-soft: a runner missing all of them
    just can't reach a peer -> reported unreachable, never a false drift alarm."""
    base = ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", "-o", "StrictHostKeyChecking=no"]
    for k in ("jarry_access", "jay_access", "fleet_hearth"):
        p = os.path.join(HOME, ".ssh", k)
        if os.path.exists(p):
            base += ["-i", p]
    return base

def _parse_mcid(out):
    """'MCID <eff> <wt> <head> <orig> [<built> <pending>]' -> dict, else None.

    The trailing fields are OPTIONAL so a peer still running the 5-field snippet
    (mid-rollout, or a node whose git-sync hasn't landed this change yet) parses fine
    and is simply not build-comparable — never a crash and never a false alarm.
    """
    for line in (out or "").splitlines():
        if line.startswith("MCID "):
            parts = line.split()
            if len(parts) >= 5:
                eff = None if parts[1] in ("none", "") else parts[1]
                built = parts[5] if len(parts) >= 6 else "none"
                built = None if built in ("none", "") else built
                return {"eff": eff, "wt": parts[2], "head": parts[3], "orig": parts[4],
                        "built": built, "pending": len(parts) >= 7 and parts[6] == "1"}
    return None

def _collect_mc_node_ids():
    """{node_key: {reachable, eff, wt, head, orig, detail}} for every serving origin.
    Local node runs the snippet directly; peers over ssh, fail-soft. METIS_MC_PARITY_MOCK
    (a JSON path) short-circuits the whole collection for deterministic self-tests."""
    mock = os.environ.get("METIS_MC_PARITY_MOCK")
    if mock:
        try:
            return json.load(open(mock))
        except Exception as e:
            return {"_mockerror": {"reachable": False, "detail": f"mock load failed: {e}"}}
    reg = _mc_node_registry()
    me = os.environ.get("USER") or ""
    out = {}
    for key, (user, host) in reg.items():
        try:
            if me == user and os.path.isdir(os.path.join(REPO, "projects", "metis-command")):
                p = subprocess.run(["bash", "-lc", _MC_ID_SNIPPET], cwd=REPO,
                                   capture_output=True, text=True, timeout=45)
                where = "local"
            else:
                p = subprocess.run(_ssh_base() + [f"{user}@{host}", "bash -s"],
                                   input=_MC_ID_SNIPPET, capture_output=True, text=True, timeout=45)
                where = "ssh"
            parsed = _parse_mcid(p.stdout)
            if parsed is None:
                tail = (p.stderr or p.stdout or "").strip().splitlines()[-1:] or [""]
                out[key] = {"reachable": False, "eff": None,
                            "detail": f"{where}: unreachable/no identity ({tail[0][:80]})"}
            else:
                parsed["reachable"] = True
                parsed["detail"] = f"{where}: {parsed['eff']} ({parsed['wt']})"
                out[key] = parsed
        except Exception as e:
            out[key] = {"reachable": False, "eff": None, "detail": f"probe error: {e}"}
    return out

# Ordered cheapest-first: draining an already-decided redeploy is lighter than
# originating a fresh one, so it leads.
_MC_DRIFT_ACTIONS = [
    "drain the queued failover redeploy: scripts/deploy-metis-command.sh --drain-pending",
    "or redeploy so both origins ship origin/main: scripts/deploy-metis-command.sh",
    "if a drain is stuck, read why: ~/.openclaw/logs/mc-origin-drain.log "
    "(ant.mc-origin-drain should clear this within ~5min of the peer waking)",
]

# BUILD_ID values that carry no comparable identity, so they can never raise an alarm:
# a node with no frozen build at all (`next dev` / a fresh checkout serves nothing from
# .next) and next.config.ts's git-less 'mc-stable' fallback.
_MC_UNCOMPARABLE_BUILDS = ("none", "mc-stable", "dev")


def _mc_comparable_builds(nodes):
    """PURE: {node_key: built_id} for reachable origins whose frozen bundle id is real."""
    out = {}
    for k, v in nodes.items():
        if not (v.get("reachable") and v.get("eff")):
            continue
        b = v.get("built")
        if b and b not in _MC_UNCOMPARABLE_BUILDS:
            out[k] = b
    return out


def _mc_parity_verdict(nodes):
    """PURE: {node_key: {reachable, eff, ...}} -> a self-heal finding dict.
    OK when every reachable origin serves the same effective app SHA (front door is
    covered transitively — it routes across these origins, so if they agree it does
    too). Fewer than 2 reachable origins is NOT comparable -> OK-with-note, never a
    false alarm (the fail-soft requirement). Divergence -> NEEDS_HUMAN, agent tier.

    Two checks run AHEAD of that source comparison, because source parity is not what
    the front door serves (2026-08-19, the unstyled cockpit on Ant's phone):
      1. the origins disagree about the BUILT bundle — the direct cause: one origin's
         HTML names chunk hashes the other never built, so whichever origin the pool
         hands the follow-up asset GET to answers 404 and the page renders raw;
      2. a queued failover redeploy is still owed — the deploy's own record that the
         origins are knowingly out of sync. This one fires with ANY number of origins
         reachable, closing the hole where the peer being ASLEEP (the state that
         creates the marker) made the whole check 'not comparable' and pass.
    Neither keys on source-vs-build staleness: main moves without a deploy all the
    time (mc-autodeploy only fires on an Auto-Deploy trailer), so that would alarm on
    the normal case — and a false stale-serve alarm is worse than a missed one here."""
    # 1. Served-bundle drift across origins — the symptom itself.
    builds = _mc_comparable_builds(nodes)
    if len(set(builds.values())) > 1:
        per = "  ".join(f"{k}={b[:12]}" for k, b in sorted(builds.items()))
        return {"name": "mc-origin-parity", "status": NEEDS_HUMAN, "escalation": AGENT,
                "detail": f"SERVED-BUNDLE drift across origins — {per}. A page load that "
                          "straddles them 404s on its own CSS/JS chunks — the cockpit "
                          "renders as unstyled HTML.",
                "actions": _MC_DRIFT_ACTIONS}

    # 2. A queued failover redeploy the auto-drain never landed.
    owed = sorted(k for k, v in nodes.items() if v.get("pending"))
    if owed:
        return {"name": "mc-origin-parity", "status": NEEDS_HUMAN, "escalation": AGENT,
                "detail": f"queued failover redeploy still owed by {', '.join(owed)} — the "
                          "peer origin is set to rejoin the CF pool on a stale build. "
                          "ant.mc-origin-drain should have cleared this within ~5min of "
                          "the peer waking, so the drain itself is stuck.",
                "actions": _MC_DRIFT_ACTIONS}

    reachable = {k: v for k, v in nodes.items() if v.get("reachable") and v.get("eff")}
    unreach = sorted(k for k, v in nodes.items() if not (v.get("reachable") and v.get("eff")))
    if unreach:
        parts = ["{0} ({1})".format(k, nodes[k].get("detail", "")) for k in unreach]
        unreach_note = "; unreachable/skipped: " + ", ".join(parts)
    else:
        unreach_note = ""
    if len(reachable) < 2:
        names = ", ".join(sorted(reachable)) or "none"
        return {"name": "mc-origin-parity", "status": OK,
                "detail": f"build-identity parity not comparable this run — only {len(reachable)} origin(s) reachable ({names}); fail-soft, no false alarm" + unreach_note,
                "actions": []}
    shas = {v["eff"] for v in reachable.values()}
    if len(shas) == 1:
        sha = next(iter(shas))
        bundle_note = f"; bundles agree too ({next(iter(set(builds.values())))[:12]})" if builds else ""
        return {"name": "mc-origin-parity", "status": OK,
                "detail": f"all {len(reachable)} origins serving the same app {sha} ({', '.join(sorted(reachable))}); front door covered transitively" + bundle_note + unreach_note,
                "actions": []}
    per = "  ".join(f"{k}={v['eff']}({v.get('wt','?')})" for k, v in sorted(reachable.items()))
    return {"name": "mc-origin-parity", "status": NEEDS_HUMAN, "escalation": AGENT,
            "detail": f"build-identity DRIFT across origins — {per}. A stale/lagging origin is (or will be) serving a different app through the CF door." + unreach_note,
            "actions": ["redeploy so both origins ship origin/main: scripts/deploy-metis-command.sh",
                        "or drain a queued failover redeploy: scripts/deploy-metis-command.sh --drain-pending",
                        "confirm which origin is stale (wt=local = serving un-pushed WIP; a lagging origin/main app-SHA = git-sync behind)"]}

# Converging the pool is a real deploy, so the heal fires at most once per window.
# A drift that returns INSIDE the window is a bug to read, not a deploy to retry —
# same reasoning as mc-origin-drain.sh's RETRY_AFTER, and the reason this check shipped
# detection-only at first ("heavier than a daily heal should blind-fire"). What makes
# acting safe now is that the deploy self-verifies: it gates each origin's served-vs-disk
# buildId and probes the real front door, so its exit code is a verdict and not a receipt.
_MC_PARITY_HEAL_MARK = os.path.join(HOME, ".openclaw", "metis-command", "origin-parity-last-heal")
_MC_PARITY_HEAL_AFTER = int(os.environ.get("MC_PARITY_HEAL_AFTER", "1800"))


def _mc_parity_converge():
    """Run the pool-convergence deploy. Returns (fired, [action strings]).

    Synchronous and exit-code-gated on purpose. A detached spawn would let the heal
    report HEALED on a deploy that then failed, which is the one thing a heal must
    never do — so this waits for the real verdict or reports that it could not get one.
    """
    # Match the script's PATH, not its basename, and bracket the first char. Both guards
    # are load-bearing (each caught a real false-busy in test, 2026-10-12): without the
    # bracket, `pgrep -f` matches the shell running the pgrep; with only the basename it
    # also matches anything merely NAMING the script — three orphaned wait-loops polling
    # `pgrep -f "deploy-metis-command.sh"` had been pinning this true since Oct 9. Either
    # way the check reads permanently busy and the heal never fires while looking fine.
    busy, _ = sh(["bash", "-lc", "pgrep -f '[s]cripts/deploy-metis-command\\.sh' >/dev/null 2>&1"])
    if busy == 0:
        return False, ["SKIP: a pool deploy is already running — letting it finish"]
    now = int(time.time())
    try:
        last = int((open(_MC_PARITY_HEAL_MARK).read().strip() or "0"))
    except Exception:
        last = 0
    if now - last < _MC_PARITY_HEAL_AFTER:
        ago, wait = (now - last) // 60, (_MC_PARITY_HEAL_AFTER - (now - last)) // 60
        return False, [f"SKIP: converged {ago}min ago and the origins drifted again — a "
                       f"recurring drift is a cause to read, not a deploy to repeat "
                       f"(next attempt in ~{wait}min)"]
    try:
        os.makedirs(os.path.dirname(_MC_PARITY_HEAL_MARK), exist_ok=True)
        open(_MC_PARITY_HEAL_MARK, "w").write(str(now))
    except Exception as e:
        return False, [f"SKIP: could not record the attempt marker ({e}) — refusing to "
                       "deploy without backoff state"]
    # 76s on the measured both-origin run; 420 leaves room for a cold npm install.
    rc, out = sh(["bash", "-lc", f"exec '{REPO}/scripts/deploy-metis-command.sh'"], timeout=420)
    if rc != 0:
        tail = " / ".join([ln.strip() for ln in out.strip().splitlines()[-3:] if ln.strip()])
        return True, [f"FAILED: pool convergence deploy exited {rc} — {tail[:300]}"]
    return True, ["converged both CF-pool origins: scripts/deploy-metis-command.sh (exit 0)"]


def check_mc_origin_parity(apply):
    """Post-deploy build-identity parity across the CF-pool origins (#2249).

    With --apply this now CONVERGES the pool instead of only reporting it, because
    nothing else closes the case that actually recurs.

    mc-origin-drain.sh covers ONE cause well: a deploy that found the peer asleep
    writes a pending marker, and the drain lands that queued redeploy once the peer
    answers (it runs on whichever machine holds the marker and ssh-es to the other —
    so an absent marker and an empty log on the peer are correct, not a stuck drain;
    an earlier read of mine called that a bug and it was not).

    What nothing covered is a STALE origin/main REF on a serving host. next.config.ts
    derives the buildId from the cockpit tree sha at the machine's own origin/main
    (stableBuildId, from the buildId-pinning work #1080), which makes that ref a build
    INPUT: a host whose fetch is behind rebuilds an older sha, and every gate passes,
    because each gate compares served-vs-disk WITHIN one origin. No marker is written,
    so the drain has nothing to act on. Measured 2026-10-12 — a both-origin deploy
    exited 0 with ORIGIN-OK on each origin while the pool stayed split on two buildIds,
    and a second full deploy moved neither. The symptom is Ant's phone rendering the
    cockpit as unstyled HTML, because a page load straddling two origins 404s the chunk
    hashes its own HTML names.

    Acts only on a real divergence, at most once per window, and RE-MEASURES afterwards
    so the verdict reports what the origins actually serve now rather than what the
    deploy claimed. NOTE the limit this implies: converging from a stale ref cannot
    work, so deploy-metis-command.sh now ORIGIN-FAILs on a failed fetch (004c6b7919)
    and this heal will surface that refusal rather than silently re-shipping the same
    split. A clean deploy that leaves the pool split means the ref, not the deploy.
    """
    v = _mc_parity_verdict(_collect_mc_node_ids())
    if not apply or v["status"] != NEEDS_HUMAN:
        return v
    fired, acted = _mc_parity_converge()
    if not fired:
        v["actions"] = acted + v["actions"]
        return v
    after = _mc_parity_verdict(_collect_mc_node_ids())
    if after["status"] == OK and all("FAILED" not in a for a in acted):
        return {"name": "mc-origin-parity", "status": HEALED, "escalation": AGENT,
                "detail": f"converged the CF-pool origins — was: {v['detail']}",
                "actions": acted}
    # Still diverged after a clean deploy: the buildId INPUT is stale on some host, so
    # redeploying just rebuilds the same wrong sha. Point at the ref, not the deploy.
    after["actions"] = acted + [
        "a clean deploy did NOT converge the pool — the buildId comes from each host's "
        "OWN origin/main ref, so compare 'git rev-parse origin/main:projects/metis-command' "
        "per origin against the real remote tip; the host that disagrees has a stale/failing "
        "fetch (check its git-sync) and will keep rebuilding that sha until the ref catches up",
    ] + after["actions"]
    return after


