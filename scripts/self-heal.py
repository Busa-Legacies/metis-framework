def _mint_governed_task(class_name, entries, tasks_path=None, alloc_id_fn=None, create_task_fn=None):
    """Mint ONE governed root-cause task for a self-heal class that crossed the firing
    threshold, embedding the recent firing history in why/how (origin=system). Never
    mints while an open task for the class already exists. `alloc_id_fn`/`create_task_fn`
    are injectable for tests; entries is a list of {"ts", "detail"} dicts (newest last)."""
    existing = _existing_open_mint_task(class_name, tasks_path)
    if existing:
        return {"class": class_name, "action": "skipped", "reason": f"open task {existing} already exists"}
    alloc_id_fn = alloc_id_fn or _default_alloc_id
    create_task_fn = create_task_fn or _default_create_task
    try:
        task_id = alloc_id_fn()
        if not task_id:
            return {"class": class_name, "action": "mint-failed", "reason": "alloc-id failed"}
        history = "\n".join(f"- {e.get('ts','?')}: {(e.get('detail') or '(no detail)')[:200]}"
                             for e in entries[-10:])
        n = len(entries)
        title = re.sub(r"-{2,}", "-", re.sub(r"[^a-z0-9-]", "-", class_name.lower())).strip("-")
        title = f"root-cause-self-heal-{title}"[:60].rstrip("-")
        summary = (f"Self-heal class '{class_name}' fired {n}x within a rolling "
                   f"{FIRING_WINDOW_DAYS}-day window — root-cause it, don't keep band-aiding.")[:400]
        why = (f"Self-heal firing-economics auto-mint (#298): the '{class_name}' self-heal check "
               f"fired {n} time(s) inside a rolling {FIRING_WINDOW_DAYS}-day window, crossing the "
               f"{FIRING_THRESHOLD}x threshold. A self-heal that keeps re-firing is treating a "
               f"symptom repeatedly instead of the underlying cause being fixed once. Firing "
               f"history:\n{history}")
        how = (f"Investigate the ROOT CAUSE of why '{class_name}' keeps firing in scripts/self-heal.py "
               f"(not just the individual instances the heal already handles) and fix it so the class "
               f"stops recurring. Do not silence/suppress the check itself. Firing history:\n{history}")
        patch = {
            "taskId": task_id, "title": title, "priority": "P3", "state": "queued",
            "owner": "either", "project": "ops", "area": "OpenClaw Infrastructure",
            "agent": "claude", "machine": "either",
            "summary": summary, "why": why, "how": how,
            "origin": "system", "originRef": f"self-heal-auto-mint:{class_name} ({_now()})",
        }
        ok, out = create_task_fn(patch)
        if not ok:
            return {"class": class_name, "action": "mint-failed", "reason": (out or "")[:300]}
        return {"class": class_name, "action": "minted", "taskId": task_id, "reason": (out or "").strip()[:160]}
    except Exception as e:
        return {"class": class_name, "action": "mint-failed", "reason": f"{type(e).__name__}: {e}"}


def track_self_heal_economics(heals, meters, apply, tasks_path=None, ledger_path=None,
                               alloc_id_fn=None, create_task_fn=None):
    """#298: count self-heal firings (heal status != OK, meter status ALERT) per class in
    a rolling FIRING_WINDOW_DAYS window; a class crossing FIRING_THRESHOLD mints ONE
    governed root-cause task via _mint_governed_task. Fail-safe: wrapped end-to-end so a
    ledger/mint problem never crashes the self-heal run. Writes the ledger only in apply
    mode (same convention as sync_worklist/autodispatch_worklist) — dry-run reports
    what firings are known so far without recording a new one."""
    try:
        details = {h["name"]: h.get("detail", "") for h in heals}
        details.update({m["name"]: m.get("detail", "") for m in meters})
        fired = sorted({h["name"] for h in heals if h["status"] != OK}
                       | {m["name"] for m in meters if m["status"] == ALERT})
        # A check can SELF-DECLARE that a recurring firing is a genuine standing condition,
        # not a band-aid loop or a check bug — so the generic "root-cause the CHECK" mint is
        # the wrong target (#298 over-mint). This keeps the exemption WITH the check (it can't
        # drift from a far-away name set) and covers meters like evergreen-pulse that already
        # have a dedicated, correct minter. The firing is still LEDGERED (honest history); only
        # the generic root-cause mint is skipped. A HEAL that keeps failing, or a check bug that
        # keeps false-firing, is NOT exempt — that is exactly what the generic mint is for.
        declared_exempt = {r["name"] for r in list(heals) + list(meters)
                           if r.get("firing_economics_exempt")}
        exempt = FIRING_ECONOMICS_EXEMPT | declared_exempt
        ledger = _load_firing_ledger(ledger_path)
        now, cutoff = _now(), _days_ago(FIRING_WINDOW_DAYS)
        if apply:
            for name in fired:
                entries = [e for e in ledger.get(name, []) if e.get("ts", "") >= cutoff]
                entries.append({"ts": now, "detail": (details.get(name) or "")[:200]})
                ledger[name] = entries
        # Prune every class down to its in-window entries (drops classes with none).
        ledger = {k: v for k, v in
                  ((k, [e for e in v if e.get("ts", "") >= cutoff]) for k, v in ledger.items())
                  if v}
        minted = []
        for name, entries in ledger.items():
            if name in exempt:
                continue
            # Only mint for a class FIRING ON THIS RUN. A class that is green now — even with
            # >=FIRING_THRESHOLD historical in-window firings — is resolved (or intermittent),
            # and minting off stale ledger history is what caused the close->re-mint churn
            # (#298): closing a fixed class's root-cause task left its 30-day window history
            # intact, so the very next run instantly re-minted (the dedup guard only blocks
            # while a task is OPEN). Requiring a current firing means a genuinely recurring
            # problem still mints the next time it actually fires, while a fixed+closed one
            # stays closed. `fired` already excludes exempt-status/OK checks.
            if name in fired and len(entries) >= FIRING_THRESHOLD:
                minted.append(_mint_governed_task(name, entries, tasks_path, alloc_id_fn, create_task_fn))
        if apply:
            _save_firing_ledger(ledger, ledger_path)
        return minted
    except Exception as e:
        return [{"class": "self-heal-economics", "action": "error", "reason": f"{type(e).__name__}: {e}"}]


# --- evergreen-pulse: auto-mint a claimable pulse-pass task (#1023 root cause) -----
# meter_evergreen_pulse is detective-only BY DESIGN — a pulse pass is judgment
# (re-assess milestone fills, then stamp lastPulseAt), never auto-derived or
# auto-stamped (project-progress-contract.md §7). That's correct and stays unchanged.
# But #1023 root-caused why a due/overdue catchment never actually gets re-pulsed:
# the ALERT only ever reached a session as one buried, non-command line inside the
# ~18-item self-heal worklist dump injected at session-init — never as claimable,
# trackable work in tasks.json like everything else in the /free-work + /next flow.
# It silently aged from due -> overdue for 7 straight daily runs (2026-07-21 to
# 2026-07-27) before the generic 3x/30d economics mint fired (which only asks
# someone to "root-cause the check" — the wrong target, since the check itself is
# fine). Fix: mint ONE governed, claimable task per due/overdue catchment (dedup-
# guarded on an open task per catchment) with the exact remediation command embedded,
# so the pulse pass becomes real, pickable, trackable-to-done work instead of a line
# that's easy to skim past. Never mints for a "current" catchment, and never widens
# or suppresses the meter itself.
AREA_BY_PROJECT = {"ops": "OpenClaw Infrastructure", "personal": "Personal & Life"}


def _existing_open_pulse_task(slug, tasks_path=None):
    """Dedupe guard mirroring _existing_open_mint_task, keyed per catchment slug so
    'ops' and 'personal' pulses are tracked independently."""
    marker = f"evergreen-pulse-mint:{slug}"
    try:
        data = json.load(open(tasks_path or TASKS_JSON))
    except Exception:
        return None
    for t in data.get("tasks", []):
        if (t.get("origin") == "system"
                and str(t.get("originRef") or "").startswith(marker)
                and t.get("state") not in CLOSED_TASK_STATES):
            return t.get("taskId")
    return None


def _mint_pulse_task(slug, pu, tasks_path=None, alloc_id_fn=None, create_task_fn=None):
    """Mint ONE governed task asking a session to do the pulse pass for `slug`
    (pu = pulse_state() result). Never mints while an open pulse-pass task for this
    catchment already exists."""
    existing = _existing_open_pulse_task(slug, tasks_path)
    if existing:
        return {"class": f"evergreen-pulse:{slug}", "action": "skipped",
                "reason": f"open task {existing} already exists"}
    alloc_id_fn = alloc_id_fn or _default_alloc_id
    create_task_fn = create_task_fn or _default_create_task
    try:
        task_id = alloc_id_fn()
        if not task_id:
            return {"class": f"evergreen-pulse:{slug}", "action": "mint-failed", "reason": "alloc-id failed"}
        cadence = pu.get("cadence") or "?"
        days = pu.get("daysSince")
        when = f"{days}d since pulse" if days is not None else "never pulsed"
        cmd = (f"python3 scripts/update-tier1-state.py update-project --slug {slug} --actor <you> "
               f'--patch \'{{"pulse": {{"cadence": "{cadence}", "lastPulseAt": "<today YYYY-MM-DD>"}}}}\'')
        title = f"pulse-pass-{slug}"[:60]
        summary = (f"Evergreen catchment '{slug}' is {pu['state']} for its {cadence} pulse "
                   f"({when}) — do the pulse pass.")[:400]
        why = (f"Evergreen catchments carry a cadence health-pulse instead of percent-complete "
               f"(project-progress-contract.md §7). '{slug}' is {pu['state']}: the last "
               f"re-assessment aged past the {cadence} window. A pulse pass is judgment, never "
               f"auto-derived/auto-stamped, so self-heal's evergreen-pulse meter only detects "
               f"staleness — it can't fix it. Root cause of the repeat firing (#1023): nothing "
               f"made that fix CLAIMABLE work, so it kept aging past due with no task ever picking "
               f"it up.")
        how = (f"Re-assess each health-pulse milestone's fill against its doneWhen for '{slug}' "
               f"(python3 scripts/update-tier1-state.py update-milestone --slug {slug} "
               f"--milestone-id <Mn> --actor <you> --patch '{{\"fill\": <0..1>}}'), then stamp the "
               f"pass:\n{cmd}\nNever stamp lastPulseAt without actually re-assessing the fills.")
        patch = {
            "taskId": task_id, "title": title, "priority": "P3", "state": "queued",
            "owner": "either", "project": slug,
            "area": AREA_BY_PROJECT.get(slug, "Uncategorized"),
            "agent": "claude", "machine": "either",
            "summary": summary, "why": why, "how": how,
            "origin": "system", "originRef": f"evergreen-pulse-mint:{slug} ({_now()})",
        }
        ok, out = create_task_fn(patch)
        if not ok:
            return {"class": f"evergreen-pulse:{slug}", "action": "mint-failed", "reason": (out or "")[:300]}
        return {"class": f"evergreen-pulse:{slug}", "action": "minted", "taskId": task_id,
                "reason": (out or "").strip()[:160]}
    except Exception as e:
        return {"class": f"evergreen-pulse:{slug}", "action": "mint-failed", "reason": f"{type(e).__name__}: {e}"}


def track_evergreen_pulse_tasks(meters, apply, tasks_path=None, projects_path=None,
                                 alloc_id_fn=None, create_task_fn=None):
    """Mint a claimable pulse-pass task for every due/overdue evergreen catchment
    reported by meter_evergreen_pulse. Fail-safe end-to-end (a bug here must never
    crash self-heal) and a no-op in dry-run, matching track_self_heal_economics'
    convention. Never mints for 'current'/'unscheduled' — only genuinely stale pulses."""
    if not apply:
        return []
    try:
        m = next((x for x in meters if x.get("name") == "evergreen-pulse"), None)
        if not m or m.get("status") != ALERT:
            return []
        _lib = os.path.join(REPO, "scripts")
        if _lib not in sys.path:
            sys.path.insert(0, _lib)
        from lib.progress import pulse_state
        with open(projects_path or os.path.join(REPO, "docs/process/state/projects.json"),
                  encoding="utf-8") as f:
            projs = json.load(f)["projects"]
        minted = []
        for p in projs:
            pu = pulse_state(p)
            if pu and pu["state"] in ("due", "overdue"):
                minted.append(_mint_pulse_task(p.get("slug"), pu, tasks_path, alloc_id_fn, create_task_fn))
        return minted
    except Exception as e:
        return [{"class": "evergreen-pulse-mint", "action": "error", "reason": f"{type(e).__name__}: {e}"}]


# --- converging fleet dedup for self-heal auto-mints (#298 + #1023) ----------------
# Both mint paths (_existing_open_mint_task / _existing_open_pulse_task) dedup against the
# LOCAL tasks.json only. When a node is diverged or offline (e.g. <<MACHINE_2_ID>> 485 commits behind
# on 2026-08-15), its self-heal can't see peers' mints, so each node mints its own task for the
# same logical fix; the taskstate UNION merge then keeps every distinct id (evergreen-pulse-mint:
# personal landed 3x — #2585/#2746/#2748). Mint-time dedup structurally can't catch a blind
# offline mint, so converge it AFTER sync: group open origin=system mint tasks by their marker
# prefix and drop all but one. Idempotent, fail-safe, no-op in dry-run.
_MINT_MARKERS = ("self-heal-auto-mint:", "evergreen-pulse-mint:")
# Only unstarted dups are dropped — never yank a dup a human has already claimed/started.
DROPPABLE_DUP_STATES = {"queued", "open", "inbox"}


def _tnum(tid):
    try:
        return int(re.sub(r"\D", "", tid or "") or "0")
    except Exception:
        return 0


def _default_drop_task(task_id, revision, reason):
    rc, out = sh([sys.executable, os.path.join(REPO, "scripts", "update-tier1-state.py"),
                  "task-update", "--actor", "self-heal", "--task-id", task_id,
                  "--expected-revision", str(revision),
                  "--patch", json.dumps({"state": "dropped", "blockerOrNone": reason})], timeout=60)
    return rc == 0, out


def dedupe_auto_mint_tasks(apply, tasks_path=None, drop_fn=None):
    """Collapse cross-machine duplicate self-heal auto-mint tasks that share an originRef
    marker (the pattern mint-time dedup can't prevent — see block comment above). Keeps one
    per marker (an actively-owned dup if any, else the earliest-created) and drops the rest,
    but ONLY dups still in an unstarted state so claimed/in-progress work is never yanked.
    drop_fn is injectable for tests; returns a per-action result list. No-op in dry-run."""
    if not apply:
        return []
    try:
        data = json.load(open(tasks_path or TASKS_JSON))
    except Exception as e:
        return [{"action": "error", "reason": f"{type(e).__name__}: {e}"}]
    groups = {}
    for t in data.get("tasks", []):
        if t.get("origin") != "system":
            continue
        ref = str(t.get("originRef") or "")
        if not ref.startswith(_MINT_MARKERS):
            continue
        if t.get("state") in CLOSED_TASK_STATES:
            continue
        groups.setdefault(ref.split(" (")[0], []).append(t)
    drop_fn = drop_fn or _default_drop_task
    results = []
    for marker, ts in groups.items():
        if len(ts) < 2:
            continue
        ts_sorted = sorted(ts, key=lambda t: (t.get("createdAt") or "", _tnum(t.get("taskId"))))
        owned = [t for t in ts_sorted if t.get("state") not in DROPPABLE_DUP_STATES]
        keep = owned[0] if owned else ts_sorted[0]
        for dup in ts_sorted:
            if dup.get("taskId") == keep.get("taskId"):
                continue
            if dup.get("state") not in DROPPABLE_DUP_STATES:
                results.append({"marker": marker, "kept": keep.get("taskId"),
                                "dup": dup.get("taskId"), "action": "kept-active"})
                continue
            reason = (f"Duplicate self-heal auto-mint of '{marker}' — canonical open task is "
                      f"{keep.get('taskId')} (kept). Cross-machine blind mint: #298/#1023 mint "
                      f"dedup only sees local tasks.json, so a diverged/offline node re-mints.")
            ok, out = drop_fn(dup.get("taskId"), dup.get("revision"), reason)
            results.append({"marker": marker, "kept": keep.get("taskId"),
                            "dropped": dup.get("taskId"),
                            "action": "dropped" if ok else "drop-failed",
                            "reason": None if ok else (out or "")[:160]})
    return results


def _meter_actions(m):
    """Build worklist action strings from a meter's samples. Samples are
    meter-specific: signoff-compliance emits dicts ({session, tail, ...}); the
    taxonomy / inbox-quality / arbiter-format meters emit plain strings. Format by
    shape so one string-sample meter can't crash the whole harness (the prior code
    assumed every sample was a signoff dict and died on the first non-signoff ALERT)."""
    acts = []
    for s in m.get("samples", []):
        if isinstance(s, dict) and "session" in s:
            sess = s.get("session", "?")
            tail = (s.get("tail", "") or "")[-120:]
            acts.append(f"FP-candidate {sess}: tune gate regex — tail `{tail}`")
        elif isinstance(s, dict) and "file" in s:
            # doc-truth-shaped sample: {file, line, kind, text}
            acts.append(f"{s.get('kind','drift')} {s.get('file','?')}:{s.get('line','?')} — {s.get('text','')}")
        elif isinstance(s, dict):
            acts.append(json.dumps(s)[:160])
        else:
            acts.append(str(s))
    return acts


