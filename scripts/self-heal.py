def _plist_content_matches(expected: str, live: str) -> bool:
    """True if the live installed plist matches what the repo would install (both are
    plist_subst output of the same source), IGNORING secret slots — a line carrying the
    __SET_IN_LOCAL_PLIST__ sentinel in `expected` is filled with the real secret in `live`
    (install-launchagents.sh carries it forward), so comparing it verbatim would false-flag
    drift. Line-count mismatch is unambiguous drift."""
    e, l = expected.splitlines(), live.splitlines()
    if len(e) != len(l):
        return False
    return all("__SET_IN_LOCAL_PLIST__" in a or a.rstrip() == b.rstrip() for a, b in zip(e, l))


def _converge_undeclared_agents(loaded, declared, host, apply):
    """Option 3 (fleet-convergence): surface a loaded agent in the fleet namespace
    (ant./<<MACHINE_2_USER>>./ai.openclaw.) that is NOT in this machine's declared roster — either
    intentional local work or a stale leftover, and only the machine's own next session can
    tell. Uses a per-host baseline (docs/process/state/launchd-baseline/<host>.json) of
    accepted-unmanaged labels: the FIRST run SEEDS it from whatever is currently running (no
    noise from the ~30 legitimately-unmanaged agents each node runs), and a NEWLY-appearing
    undeclared agent thereafter is reported in the self-heal worklist EVERY run until a session
    resolves it (declare into config/infrastructure.json, accept into the baseline file, or
    unload + remove its plist). No fleet-notify: that tool refuses self-notification, and the
    self-heal worklist is already the local delivery channel. Self-scoped — reads/writes only
    THIS machine's own state (cross-machine-observation-protocol). Returns
    {"new": [...], "note": str}."""
    NS = ("ant.", "<<MACHINE_2_USER>>.", "ai.openclaw.")
    dset = set(declared)
    undeclared = sorted(l for l in loaded if l.startswith(NS) and l not in dset)
    if not host:
        return {"new": [], "note": "host unknown — undeclared scan skipped"}
    base_dir = os.path.join(REPO, "docs", "process", "state", "launchd-baseline")
    base_path = os.path.join(base_dir, f"{host}.json")
    baseline = None
    if os.path.exists(base_path):
        try:
            baseline = set(json.load(open(base_path)).get("unmanaged", []))
        except Exception:
            baseline = None
    _NOTE = ("accepted-unmanaged launchd agents (loaded, in the fleet namespace, but not in "
             "this machine's convergence roster in config/infrastructure.json). A newly-"
             "appearing undeclared agent is reported in the self-heal worklist every run until "
             "a session resolves it: declare it into the roster, accept it by adding it to this "
             "file's `unmanaged` list, or unload + remove its plist.")
    if baseline is None:
        # First run: SEED from whatever is currently running — the accepted status quo, so the
        # ~30 legitimately-unmanaged agents each node runs never blast the worklist.
        if apply:
            os.makedirs(base_dir, exist_ok=True)
            with open(base_path, "w") as fh:
                json.dump({"unmanaged": undeclared, "_note": _NOTE}, fh, indent=2)
            return {"new": [], "note": f"seeded baseline ({len(undeclared)} unmanaged)"}
        return {"new": [], "note": f"no baseline yet ({len(undeclared)} undeclared — would seed)"}
    new = sorted(set(undeclared) - baseline)
