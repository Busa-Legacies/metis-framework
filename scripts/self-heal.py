# ── load-spike / runaway-process detector (#479) ──────────────────────────────
# The #471 pre-push-gate fork bomb drove <<MACHINE_1_ID>> to load ~480 and starved the tailnet; it
# was only caught when Ant saw Metis unreachable on his phone. This samples the 1-min load
# average + process count twice; the runaway-spawn (fork-bomb) signature is HIGH load AND a
# rapidly climbing process count across the samples. Detection + phone alert is the primary
# value; an auto-kill of the runaway subtree is OPT-IN (LOAD_SPIKE_AUTOKILL=1) and NEVER
# targets a protected core-service signature.
LOAD_SPIKE_THRESHOLD = float(os.environ.get("LOAD_SPIKE_THRESHOLD", "80"))    # normal <<MACHINE_1_ID>> < ~20; #471 hit ~480
PROC_GROWTH_THRESHOLD = int(os.environ.get("PROC_GROWTH_THRESHOLD", "120"))   # new procs between the two samples
_LOAD_SPIKE_PROTECTED = ("launchd", "windowserver", "loginwindow", "kernel_task", "tailscaled",
                         "tailscale", "sshd", "mlx_lm.server", "mlx", "uvicorn", "python3.14",
                         "ollama", "caddy", "postiz", "searxng", "openclaw", "claude", "node", "finder")


def _load_spike_verdict(load1, proc_counts):
    """Pure decision (testable without a real fork bomb): given the 1-min load average and a
    series of process counts sampled over time, return a fork-bomb finding dict or None.
    Fires ONLY when load is high AND the process count is climbing fast — high load alone is a
    heavy compute job, not a runaway spawn, and must never trip this meter."""
    if load1 is None or load1 < LOAD_SPIKE_THRESHOLD:
        return None
    if len(proc_counts) < 2:
        return None
    growth = proc_counts[-1] - proc_counts[0]
    if growth < PROC_GROWTH_THRESHOLD:
        return None
    return {"load": round(load1, 1), "growth": growth, "procs": proc_counts[-1]}


def _runaway_signature(limit=5):
    """Best-effort culprit id: tally the most common command name among the highest PIDs — a
    fork bomb's descendants dominate the newest slice of the PID space. Returns [(comm, count)]."""
    from collections import Counter
    rc, out = sh(["ps", "-axo", "pid=,comm="], timeout=10)
    if rc != 0 or not out:
        return []
    rows = []
    for ln in out.splitlines():
        pid, _, comm = ln.strip().partition(" ")
        try:
            rows.append((int(pid), os.path.basename(comm.strip())))
        except ValueError:
            continue
    rows.sort(key=lambda r: r[0], reverse=True)          # newest PIDs first
    return Counter(c for _, c in rows[:400]).most_common(limit)


# Trees a package manager, browser or build cache owns. They are legitimately large and
# legitimately old -- their staleness is install date, not a leak -- and our cleaners do not
# own them, so measuring them only produces noise.
_UNPRUNED_SKIP = ("/site-packages/", "/node_modules/", "/venv/", "/.venv/", "/.git/",
                  "/node-compile-cache/", "/browser-profile/", "/.cache/uv/",
                  "/Cache_Data/", "/jiti/")


def check_unpruned_dirs(apply):
    """#4401: catch the failure mode shared by the file-guard marker leak (#3945) and the
    session-prune gap (#4397) -- a directory quietly filling with dead files while the cleanup
    that is meant to cover it runs on schedule and reports success. In both cases the cleaner's
    own output said it was working, so nothing ever surfaced; the dirs reached 13,290 and
    ~32,800 files respectively.

    Neither was a directory anyone was watching, so this checks the OUTCOME -- is anything
    accumulating? -- rather than any particular cleaner, and needs no watchlist to maintain.
    The discriminator is STALENESS, not size: a healthy high-churn dir is mostly recent files,
    a leaking one is mostly old ones. Size alone false-positives on lanes with genuinely high
    recent volume (smith legitimately holds ~6.8k files inside its 30-day retention)."""
    roots = [os.path.expanduser(p) for p in ("~/.claude", "~/.openclaw")]
    min_files = int(os.environ.get("METIS_UNPRUNED_MIN_FILES", "1000"))
    stale_days = int(os.environ.get("METIS_UNPRUNED_STALE_DAYS", "45"))
    min_frac = float(os.environ.get("METIS_UNPRUNED_STALE_FRAC", "0.5"))
    # Absolute ceiling (#4405): staleness alone only catches SLOW leaks. <<MACHINE_2_ID>> held 45,829
    # orphaned temps that were all newer than the staleness window, so it read as 100% recent
    # and this check passed it. A dir this large is pathological at any age -- no working set
    # here is legitimately five figures (the busiest healthy lane sits ~6.8k inside retention).
    ceiling = int(os.environ.get("METIS_UNPRUNED_CEILING", "10000"))
    cutoff = time.time() - stale_days * 86400

    # pass 1: cheap entry counts, pruning owned trees as we go (no stat calls yet)
    big = []
    for root in roots:
        if not os.path.isdir(root):
            continue
        for dirpath, dirnames, filenames in os.walk(root):
            if any(m in dirpath + "/" for m in _UNPRUNED_SKIP):
                dirnames[:] = []
                continue
            if len(filenames) >= min_files:
                big.append((dirpath, filenames))

    # pass 2: stat only the dirs already over the threshold
    flagged = []
    for dirpath, filenames in big:
        stale = 0
        for n in filenames:
            try:
                if os.path.getmtime(os.path.join(dirpath, n)) < cutoff:
                    stale += 1
            except OSError:
                continue
        frac = stale / float(len(filenames))
        if frac >= min_frac or len(filenames) >= ceiling:
            flagged.append((dirpath, len(filenames), stale, frac))

    if not flagged:
        return {"name": "unpruned-dirs", "status": OK,
                "detail": f"{len(big)} dir(s) over {min_files} files, none majority-stale",
                "actions": []}

    flagged.sort(key=lambda r: -r[1])
    home = os.path.expanduser("~")
    actions = [f"{d.replace(home, '~')}: {n} files, {st} ({f:.0%}) older than {stale_days}d -- "
               + ("over the {0} ceiling; a fast leak reads as 'recent'".format(ceiling)
                  if n >= ceiling and f < min_frac else "nothing is pruning this")
               for d, n, st, f in flagged]
    actions.append("verify the cleaner that owns the dir actually MATCHES what is in it -- in "
                   "#4397 the session prune globbed *.jsonl, missed 87% of the files, and "
                   "reported success every day for months")
    return {"name": "unpruned-dirs", "status": NEEDS_HUMAN,
            "detail": f"{len(flagged)} dir(s) accumulating dead files", "actions": actions}


def check_load_spike(apply):
    """Layer-B meter (#479): detect a runaway process-spawn (fork-bomb) signature — HIGH 1-min
    load AND a rapidly climbing process count — and alert Ant. Auto-kill of the runaway subtree
    is opt-in (LOAD_SPIKE_AUTOKILL=1) and never targets a protected core-service comm."""
    try:
        load1 = os.getloadavg()[0]
    except (OSError, AttributeError):
        return {"name": "load-spike", "status": OK, "detail": "loadavg unavailable (ignored)", "actions": []}

    def _proc_count():
        rc, out = sh(["ps", "-A", "-o", "pid="], timeout=10)
        return len([l for l in out.splitlines() if l.strip()]) if rc == 0 else 0

    samples = [_proc_count()]
    time.sleep(1.2)                                       # catch a count that is still climbing
    samples.append(_proc_count())

    verdict = _load_spike_verdict(load1, samples)
    if not verdict:
        return {"name": "load-spike", "status": OK,
                "detail": f"load {load1:.1f} / {samples[-1]} procs (Δ{samples[-1]-samples[0]}) — normal",
                "actions": []}

    sig = _runaway_signature()
    sig_str = ", ".join(f"{c}×{n}" for n, c in sig) if sig else "unidentified"
    actions = [
        "identify the runaway chain (protecting core services): ps -axo pid,ppid,comm | sort -rn | head",
        "root cause: an unbounded fork/subprocess loop (see the #471 pre-push-gate fork bomb)",
    ]
    killed = []
    if apply and os.environ.get("LOAD_SPIKE_AUTOKILL") == "1" and sig:
        top_comm = sig[0][0]
        if top_comm.lower() not in (p.lower() for p in _LOAD_SPIKE_PROTECTED):
            sh(["pkill", "-TERM", "-f", top_comm], timeout=10)
            killed.append(top_comm)
            actions.insert(0, f"AUTO-KILLED runaway signature '{top_comm}' (pkill -TERM); confirm load recovers")
    return {"name": "load-spike", "status": NEEDS_HUMAN, "escalation": ANT,
            "detail": (f"RUNAWAY-SPAWN SIGNATURE: load {verdict['load']} (>{LOAD_SPIKE_THRESHOLD:.0f}), "
                       f"procs {verdict['procs']} climbing +{verdict['growth']} in ~1.2s. "
                       f"Newest-PID culprits: {sig_str}." + (f" AUTO-KILLED: {killed}" if killed else "")),
            "actions": actions}


