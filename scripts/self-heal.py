def check_stray_git(apply):
    """Nested .git dirs under projects/ cause wrong-dir writes / silent git failures —
    but ONLY when the outer repo doesn't ignore them. A gitignored nested repo (e.g.
    projects/polymarket-bot, a deliberate public/private carveout with its own remotes)
    is intentional and invisible to outer-repo git ops, so it's NOT a stray. Flag only
    nested .git dirs the outer repo does NOT ignore."""
    rc, out = sh(["bash", "-lc", f"find '{REPO}/projects' -name .git -maxdepth 3 2>/dev/null"])
    strays = []
    for line in out.splitlines():
        d = line.strip()
        if not d:
            continue
        rel = os.path.relpath(d, REPO)
        # outer repo ignores it → deliberate separate repo, not a stray
        ig, _ = sh(["bash", "-lc", f"git -C '{REPO}' check-ignore -q '{rel}'"])
        if ig != 0:
            strays.append(rel)
    if not strays:
        return {"name": "stray-git", "status": OK, "detail": "no un-ignored nested .git under projects/", "actions": []}
    return {"name": "stray-git", "status": NEEDS_HUMAN,
            "detail": f"{len(strays)} un-ignored nested .git dir(s)",
            "actions": [f"investigate {r} — gitignore it (if intentional) or register as submodule" for r in strays]}


def check_gitsync_drift(apply):
    """Live git-sync script vs canonical + heartbeat (the 2026-05-30 corruption class).
    Script/heartbeat drift stays detection-only — which side is canonical is a
    judgment call.  Orphaned daemon stashes are different: the reconciler archives
    risky content before dropping, so daily --apply can clear that mechanical class
    before it accumulates into another sync wedge."""
    rc, out = sh(["bash", os.path.join(REPO, "scripts", "check-sync-drift.sh")])
    if rc == 0:
        return {"name": "gitsync-drift", "status": OK, "detail": "live git-sync matches canonical + healthy", "actions": []}
    if apply and "STASH:" in out:
        r2, o2 = sh([sys.executable, os.path.join(REPO, "scripts", "reconcile-daemon-stashes.py"), "--apply"], timeout=180)
        rc3, out3 = sh(["bash", os.path.join(REPO, "scripts", "check-sync-drift.sh")])
        # Judge the drain by whether the stash class is actually cleared (no "STASH:" line
        # remains) — NOT by check-sync-drift.sh's exit code. That script ALSO fails on an
        # unrelated stale HEARTBEAT (the daemon defers pulls during active edit sessions, so
        # "last sync >15m" is routinely benign), which mislabeled 14 straight days of
        # SUCCESSFUL drains as "daemon stash auto-reconcile failed" (worklist first_seen
        # 2026-07-14 → last_seen 2026-07-27, 14 occurrences). The heartbeat/script-drift signal
        # is independent and re-surfaces on the next tick via the drift branch below once the
        # stashes are gone, so decoupling it here loses nothing.
        if r2 == 0 and "STASH:" not in out3:
            actions = [l.strip() for l in o2.splitlines() if "archived " in l or "dropped " in l or "wrote inventory" in l]
            return {"name": "gitsync-drift", "status": HEALED,
                    "detail": "auto-reconciled orphaned daemon stashes (heartbeat/drift, if any, reported separately next tick)",
                    "actions": actions[:6] or ["ran reconcile-daemon-stashes.py --apply"]}
        lines = [l.strip() for l in (o2 + "\n" + out3).splitlines() if l.strip()]
        return {"name": "gitsync-drift", "status": NEEDS_HUMAN,
                "detail": "daemon stash auto-reconcile failed",
                "actions": lines[-5:] or ["run scripts/reconcile-daemon-stashes.py manually"]}
    lines = [l.strip() for l in out.splitlines() if l.strip() and not l.startswith("OK")]
    return {"name": "gitsync-drift", "status": NEEDS_HUMAN,
            "detail": "git-sync script drift or stale heartbeat",
            "actions": lines[:4] or ["run scripts/check-sync-drift.sh and review"]}


