def _finding_hash(name, actions):
    import hashlib
    blob = str(name) + "\x00" + "\x00".join(actions or [])
    return hashlib.sha1(blob.encode("utf-8")).hexdigest()[:16]


def _default_dispatcher(lane, message, work_type, timeout=480):
    """The real guarded dispatch. Calls `scripts/dispatch` WITHOUT --approve-risk (so any
    approval-requiring risk route is REFUSED by dispatch itself, exit 2) and
    --mutation proposal-only (the lane DRAFTS a fix; nothing auto-executes). This is the
    third belt — after the allowlist and the money regex — and reuses the exact gate the
    queue-runner rides. Returns (ok: bool, detail: str)."""
    cmd = [os.path.join(REPO, "scripts", "dispatch"),
           "--agent", lane, "--message", message,
           "--timeout", str(timeout),
           "--work-type", work_type, "--mutation", "proposal-only"]
    try:
        r = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True, timeout=timeout + 60)
        if r.returncode == 0:
            return True, (r.stdout or "").strip()[:400]
        return False, f"dispatch exit {r.returncode}: {((r.stderr or r.stdout) or '').strip()[:200]}"
    except Exception as e:
        return False, str(e)


def autodispatch_worklist(items, apply, dispatcher=None):
    """#863: route SAFE, low-risk, non-money agent-tier findings to a lane via the guarded
    dispatch path, so routine self-detected fixes don't dead-end at manual pickup.

    Fail-closed gate order per item: must be ALLOWLISTED -> not MONEY-adjacent -> not
    already dispatched (same content hash) -> the guarded `scripts/dispatch` accepts it
    (it refuses approval-requiring risk routes on its own). Idempotent via a content-hashed
    ledger: a finding dispatches once per distinct action-set; a materially changed finding
    (new actions) re-dispatches. High-risk / money / non-allowlisted findings are LEFT in the
    worklist untouched for the human/interactive pickup path. Skips all writes + dispatch on
    dry-run. Returns a per-item report list; `dispatcher` is injectable for tests."""
    dispatcher = dispatcher or _default_dispatcher
    try:
        ledger = json.load(open(DISPATCH_LEDGER))
    except Exception:
        ledger = {}
    report = []
    for it in items:
        name = it.get("key") or it.get("name", "?")
        detail = it.get("title", "") or ""
        actions = it.get("actions", []) or []
        blob = detail + " " + " ".join(actions)
        if name not in AUTODISPATCH_ALLOW:
            report.append({"finding": name, "action": "skipped", "reason": "not-allowlisted (human-gated)"})
            continue
        if _MONEY_RE.search(blob):
            report.append({"finding": name, "action": "skipped", "reason": "money-adjacent"})
            continue
        h = _finding_hash(name, actions)
        prev = ledger.get(name)
        if prev and prev.get("hash") == h and prev.get("ok"):
            report.append({"finding": name, "action": "skipped", "reason": "already-dispatched"})
            continue
        if not apply:
            report.append({"finding": name, "action": "would-dispatch", "reason": "dry-run"})
            continue
        msg = (f"Self-heal auto-dispatch — bounded remediation for check '{name}'.\n"
               f"Finding: {detail}\n"
               f"Suggested actions:\n- " + "\n- ".join(actions) +
               "\n\nPropose a MINIMAL diff to resolve this. Proposal only — do NOT execute risky "
               "ops. If the fix touches money/trading/auth/secrets/launchd/git-sync, STOP and "
               "report instead of proposing.")
        ok, out = dispatcher("smith", msg, "quality")
        ledger[name] = {"hash": h, "ok": bool(ok), "at": _now(), "detail": (out or "")[:200]}
        report.append({"finding": name, "action": "dispatched" if ok else "dispatch-refused",
                       "reason": (out or "")[:160]})
    if apply:
        try:
            os.makedirs(os.path.dirname(DISPATCH_LEDGER), exist_ok=True)
            json.dump(ledger, open(DISPATCH_LEDGER, "w"), indent=2)
        except Exception:
            pass
    return report


