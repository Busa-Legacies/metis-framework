    if os.path.exists(kill_path):
        try:
            if _json.load(open(kill_path)).get("engaged"):
                problems.append("kill switch ENGAGED (order placement blocked)")
        except Exception:
            problems.append("kill switch latch unreadable (fails closed -> blocked)")

