# --- drain-clone ff-only sync wedge (#5275, 2026-08-15 post-mortem root cause 1) ------------
# A dirty live-WIP tree wedged the ff-only auto-sync pull on <<MACHINE_1_ID>>'s ~/metis-os: local
# commits accumulated (ahead 35) while origin advanced (behind 91), and the relay poller
# silently drained a checkout frozen for ~90 min. Same class as
# reference_appliance_mirror_git_sync_reset_hard ("ff-only wedges silently on local dirt →
# node drifts while the timer keeps 'firing'") — but this checkout is NOT a pure mirror: it
# can hold live WIP, so a blind `reset --hard` is forbidden. Recovery isolates the WIP first
# (stash tracked dirt + branch local commits — both fully reversible), and every destructive
# step is gated on the preceding preservation step verifiably succeeding
# (feedback_gate_destructive_git_on_prior_step_success).
DRAIN_WEDGE_MARKER = os.path.join(HOME, ".openclaw", "logs", "drain-clone-sync.ok")
DRAIN_WEDGE_MAX_BEHIND = int(os.environ.get("DRAIN_WEDGE_MAX_BEHIND", "0"))
# #5275 calibration: the primary <<MACHINE_1_ID>> ~/metis-os clone (a legitimate drain clone) shows
# behind+dirty as NORMAL auto-sync churn on almost every tick — the daemon commits WIP and is
# transiently behind between its own push/pull cycles, and that churn self-converges. Acting on
# a single-tick wedge signature therefore false-fires the WIP-isolating stash + reset on normal
# churn (observed: 7 stray `self-heal drain-wedge isolate` stashes accrued on the primary clone).
# So the destructive recovery only runs once the SAME wedge has PERSISTED past a window the
# auto-sync daemon has had ample time to converge within — a true stuck wedge, not churn. This is
# the persistence the marker docstring already promised but the action path never enforced.
DRAIN_WEDGE_PENDING = os.path.join(HOME, ".openclaw", "logs", "drain-clone-wedge.pending")
DRAIN_WEDGE_MIN_PERSIST_SEC = int(os.environ.get("DRAIN_WEDGE_MIN_PERSIST_SEC", "21600"))  # 6h


def _drain_wedge_note_pending(sig):
    """Record the first time a wedge signature was seen; return seconds since that first
    sighting (0 when brand-new this call). A healthy tick clears the record via
    _drain_wedge_touch_ok, so the age only grows while the clone stays continuously wedged.
    Any read/parse error is treated as brand-new (age 0) so a corrupt/absent marker can never
    by itself justify the destructive recovery — it fails toward NOT acting."""
    now = int(time.time())
    try:
        with open(DRAIN_WEDGE_PENDING) as f:
            first = int(json.load(f).get("first_ts", now))
    except (OSError, ValueError, TypeError, AttributeError):
        first = now
    try:
        os.makedirs(os.path.dirname(DRAIN_WEDGE_PENDING), exist_ok=True)
        with open(DRAIN_WEDGE_PENDING, "w") as f:
            json.dump({"first_ts": first, "sig": sig, "last_ts": now}, f)
    except OSError:
        pass
    return now - first


def _drain_wedge_clear_pending():
    """The clone is healthy (or recovered) — forget any pending wedge so the persistence
    counter restarts from scratch next time."""
    try:
        os.remove(DRAIN_WEDGE_PENDING)
    except OSError:
        pass


def _drain_wedge_touch_ok(detail):
    """Freshness marker for the drain-clone-sync-wedge loop contract: touched whenever the
    drain clone has no unrecovered wedge. If a wedge persists across self-heal cycles
    (recovery failing) the marker goes stale and loop-contract-lint escalates. A healthy tick
    also clears any pending-wedge persistence counter (#5275)."""
    _drain_wedge_clear_pending()
    try:
        os.makedirs(os.path.dirname(DRAIN_WEDGE_MARKER), exist_ok=True)
        with open(DRAIN_WEDGE_MARKER, "w") as f:
            f.write(f"{_now()} {detail}\n")
    except OSError:
        pass


