def heal_symlinks(apply):
    """Re-link any ~/.claude symlink declared in mirror-manifest.json that is
    broken/missing/wrong. Pure plumbing, fully reversible → safe to auto-heal."""
    manifest = os.path.join(REPO, "ClaudeCode", "mirror-manifest.json")
    actions, bad = [], 0
    # #3455: REPO is this file's own location; a run from a linked worktree must not
    # retarget ~/.claude into it (the worktree is deleted when its task lands).
    rc1, gd = sh(["git", "-C", REPO, "rev-parse", "--absolute-git-dir"])
    rc2, gcd = sh(["git", "-C", REPO, "rev-parse", "--path-format=absolute", "--git-common-dir"])
    if rc1 == 0 and rc2 == 0 and os.path.realpath(gd.strip()) != os.path.realpath(gcd.strip()):
        return {"name": "symlinks", "status": OK, "actions": [],
                "detail": f"skipped: {REPO} is a linked worktree, not the canonical clone"}
    try:
        m = json.load(open(manifest))
    except Exception as e:
        return {"name": "symlinks", "status": NEEDS_HUMAN,
                "detail": f"cannot read mirror-manifest.json: {e}", "actions": []}
    for entry in m.get("symlinks", []):
        link = os.path.expanduser(entry["link"])
        want = os.path.join(REPO, entry["target"])
        cur = os.path.realpath(link) if os.path.lexists(link) else None
        if cur == os.path.realpath(want):
            continue
        bad += 1
        if apply:
            try:
                if os.path.lexists(link):
                    os.remove(link)
                os.makedirs(os.path.dirname(link), exist_ok=True)
                os.symlink(want, link)
                actions.append(f"relinked {entry['link']} → {entry['target']}")
            except Exception as e:
                actions.append(f"FAILED relink {entry['link']}: {e}")
        else:
            actions.append(f"would relink {entry['link']} → {entry['target']}")
    if bad == 0:
        return {"name": "symlinks", "status": OK, "detail": "all manifest symlinks intact", "actions": []}
    status = HEALED if apply and all("FAILED" not in a for a in actions) else NEEDS_HUMAN
    return {"name": "symlinks", "status": status, "detail": f"{bad} symlink(s) off", "actions": actions}


def heal_hook_exec(apply):
    """Ensure every hook/bin script is executable. Lost +x silently disables a hook.

    #1028 root cause: scripts/**, ClaudeCode/hooks/**, and ClaudeCode/bin/** are SOURCE
    paths (openclaw-git-sync.sh's #234/#311 split-lane design) that the auto-sync daemon
    deliberately never auto-commits to main -- only STATE_PATHSPECS get that. A chmod
    applied here in apply mode was therefore only an uncommitted, LOCAL working-tree diff:
    fragile against the daemon's pre-pull stash/pop cycle (a stash-pop conflict falls back
    to `git reset --hard HEAD`, discarding it) and invisible to any fresh worktree or other
    machine's clone, which re-materializes the file from the still-non-exec git blob. Two
    scripts (install-people-photo-launchd.sh, people-photo-sync.sh — born non-exec at
    creation 2026-07-16/17 and never committed +x) got chmod'd and silently un-chmod'd on a
    loop for 4+ days across 3 machines, always reporting HEALED — which hid the loop from
    sync_worklist's recurrence ledger (it only sees NEEDS_HUMAN findings; HEALED never
    reaches `findings`). Fix: still chmod on disk (harmless, immediate), but if the file is
    still dirty vs HEAD afterward (nobody has committed +x into the tree), report
    NEEDS_HUMAN instead of a false HEALED so this routes through the real worklist /
    recurrence machinery until a session lands the commit — never silently "heals" the
    same uncommitted bit forever. We do NOT auto-commit here: that would cross the
    deliberate SOURCE-vs-STATE boundary (#234/#311) the daemon itself respects; landing the
    commit stays a human/session-intent action.
    """
    actions = []
    dirty = []
    for pat in ("ClaudeCode/hooks/*.sh", "ClaudeCode/bin/*.sh", "scripts/*.sh"):
        for f in glob.glob(os.path.join(REPO, pat)):
            if not os.access(f, os.X_OK):
                rel = os.path.relpath(f, REPO)
                if apply:
                    try:
                        os.chmod(f, os.stat(f).st_mode | 0o111)
                        actions.append(f"chmod +x {rel}")
                    except Exception as e:
                        actions.append(f"FAILED chmod {rel}: {e}")
                        continue
                else:
                    actions.append(f"would chmod +x {rel}")
                    continue
                # Tracked + still different from HEAD after the chmod? Then the fix is
                # only local and will NOT survive the daemon's stash/pull cycle or a fresh
                # worktree/clone — surface it as NEEDS_HUMAN rather than a false HEALED.
                rc, _ = sh(["git", "diff", "--quiet", "HEAD", "--", rel])
                if rc != 0:
                    dirty.append(rel)
    if not actions:
        return {"name": "hook-exec", "status": OK, "detail": "all scripts executable", "actions": []}
    if dirty:
        actions.append(
            "exec bit fixed on disk but NOT committed for "
            f"{len(dirty)} file(s) ({', '.join(dirty)}) — these are SOURCE paths the "
            "daemon won't auto-commit (#234); a session must `git add` + commit the mode "
            "change or this reappears next run"
        )
        return {"name": "hook-exec", "status": NEEDS_HUMAN,
                "detail": f"{len(dirty)} non-exec script(s) fixed on disk but uncommitted",
                "actions": actions}
    status = HEALED if apply and all("FAILED" not in a for a in actions) else NEEDS_HUMAN
    return {"name": "hook-exec", "status": status, "detail": f"{len(actions)} non-exec script(s)", "actions": actions}


