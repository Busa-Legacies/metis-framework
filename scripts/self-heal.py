    if os.path.exists(snap_path):
        try:
            captured = float(_json.load(open(snap_path)).get("captured_at", 0))
            age = _time.time() - captured
            if age >= 2 * max_age_s:
                problems.append(f"RH snapshot DEAD ({age/60:.0f}m old; hands job likely dead)")
        except Exception as e:
            problems.append(f"RH snapshot unreadable ({e!r})")

