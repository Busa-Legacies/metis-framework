def sync_worklist(agent_findings, apply, tasks_path=None):
    """Maintain the self-heal worklist (the agent-tier backlog the next session works).

    Upsert one entry per current agent-tier finding (keyed by check name; refresh
    last_seen + occurrences + latest actions), and AUTO-CLEAR entries whose check is
    no longer failing (the heal landed or the drift cleared). Returns the open list.
    Skips the write in dry-run so tests don't mutate state.

    Recurrence guard (2026-07-15): the plain `occurrences` counter resets on every
    auto-clear, so a fail→fix→fail→fix band-aid loop always looked brand-new — which is
    exactly why a buggy check (memory-domain false positives) got band-aided ~5× over
    10 days with no net noticing. We now retain a compact `resolved_ledger` ACROSS clears;
    once a finding reappears RECUR_THRESHOLD times inside RECUR_WINDOW_DAYS, its worklist
    entry escalates from 'fix the finding' to 'root-cause the CHECK — stop band-aiding'.

    Already-triaged guard (#1025): a finding whose class already has an OPEN root-cause
    task (minted by track_self_heal_economics/#298 — e.g. a genuine ongoing external
    blocker like the GitHub Actions billing block) must NOT keep presenting itself as
    fresh, undirected work every day. That re-mints nothing (the mint dedupe already
    handles that) but it DOES cost a session real time re-investigating an already-known,
    already-documented condition — which is exactly what happened here (#1025 fired 3
    days running while itself being the open root-cause task). The meter still ALERTs
    daily if the underlying condition is real and ongoing (that's honest, not noise) —
    only the WORKLIST framing changes, from 'go figure this out' to 'already tracked in
    <taskId>, don't re-investigate'. Stays visible (never dropped) per
    feedback_no_ignorable_visibility — just correctly labeled.
    """
    try:
        blob = json.load(open(WORKLIST))
    except Exception:
        blob = {}
    existing = {e["key"]: e for e in blob.get("items", [])}
    ledger = blob.get("resolved_ledger", {})  # key -> {resolved_count, reappearances, last_resolved}
    current_keys = {f["name"] for f in agent_findings}
    now, cutoff = _now(), _days_ago(RECUR_WINDOW_DAYS)
    tracked_tasks = _open_mint_tasks_by_class(tasks_path) if agent_findings else {}
    items = []
    for f in agent_findings:
        k = f["name"]
        prev = existing.get(k)
        led = ledger.get(k)
        # A "reappearance" = failing now, was resolved before (within window), not carried
        # over from last run. Count it once per return so an ongoing failure doesn't inflate.
        if led and not prev and led.get("last_resolved", "") >= cutoff:
            led["reappearances"] = led.get("reappearances", 0) + 1
        reapp = (led or {}).get("reappearances", 0)
        title, actions = f["detail"], list(f.get("actions", []))
        if reapp >= RECUR_THRESHOLD:
            title = f"↻ RECURRING ({reapp}× resolved & returned) — {f['detail']}"
            actions = [
                f"⚠️ ROOT-CAUSE THE CHECK, don't band-aid: '{k}' has been resolved "
                f"{led.get('resolved_count', reapp)}× and keeps returning. A gate that fires "
                f"repeatedly on valid-looking inputs is a CHECK/process bug until proven otherwise "
                f"— fix the check itself (and make the lesson a test), not the flagged item.",
            ] + actions
        tracked = tracked_tasks.get(k)
        if tracked:
            # Already root-caused and tracked — stop presenting this as fresh, undirected
            # work. The task (not this worklist entry) owns the fix/blocker from here.
            title = f"[tracked in {tracked}] {f['detail']}"
            actions = [f"Already root-caused as {tracked} (open) — do NOT re-investigate or "
                       f"spawn a duplicate task; that task owns the fix/blocker. Only act here "
                       f"if {tracked} is stale, closed-but-wrong, or no longer matches this finding."]
        entry = {
            "key": k, "title": title, "tier": AGENT, "actions": actions,
            "first_seen": prev["first_seen"] if prev else now,
            "last_seen": now,
            "occurrences": (prev["occurrences"] + 1) if prev else 1,
        }
        if reapp:
            entry["reappearances"] = reapp
        if tracked:
            entry["tracked_task"] = tracked
        items.append(entry)
    # entries not in current findings are resolved → auto-clear, but TALLY in the ledger
    # (retaining just enough to see a loop) instead of forgetting them entirely.
    cleared = [k for k in existing if k not in current_keys]
    for k in cleared:
        led = ledger.setdefault(k, {"resolved_count": 0, "reappearances": 0})
        led["resolved_count"] = led.get("resolved_count", 0) + 1
        led["last_resolved"] = now
    # Prune stale ledger keys (resolved outside the window and not currently failing).
    ledger = {k: v for k, v in ledger.items()
              if k in current_keys or v.get("last_resolved", "") >= cutoff}
    if apply:
        try:
            os.makedirs(os.path.dirname(WORKLIST), exist_ok=True)
            json.dump({"updatedAt": now, "items": items, "resolved_ledger": ledger},
                      open(WORKLIST, "w"), indent=2)
        except Exception:
            pass
    return items, cleared


