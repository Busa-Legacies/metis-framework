# Routing-signal projection (#4425). The dispatch ledger is what routing decisions and the 24h
# meters are read from, but it is tail-kept at 500 records because each one carries the full model
# output inline (~20KB). That cap is not the problem by itself -- the problem is that ONE
# experiment can flush it: a 474-call eval batch evicted all but 26 production records, and no
# routing question could be answered from what was left. Routing analysis never needs the model
# output, so evicted records are projected down to the routing fields and kept far longer. A slim
# record is ~300 bytes against ~20KB, so the same disk buys roughly 60x more history.
ROUTING_FIELDS = ("ts", "role", "engine", "engine_requested", "engine_policy_default",
                  "engine_downgraded_from", "elapsed_s", "ok", "status", "route_reason",
                  "traffic",
                  "machine", "runtime", "task_features", "verdict", "artifact_kind",
                  "output_chars", "schema",
                  # provider attribution (Ant 2026-09-03): `engine` is a TIER name, so
                  # without these the studio-vs-<<MACHINE_1_ID>> serving node is unrecoverable
                  # once a record is evicted here. Additive; old rows simply lack them.
                  "provider", "model")


def _slim_routing_record(rec):
    """Project one ledger record to the routing fields. Keeps a short task head: it is what
    distinguishes an eval probe from production traffic, which is exactly the call that could
    not be made when the ledger was flushed."""
    out = {k: rec[k] for k in ROUTING_FIELDS if k in rec}
    task = rec.get("task")
    if isinstance(task, str) and task:
        out["task_head"] = task[:120]
    return out


def heal_log_rotation(apply):
    """#795 (full-sweep-2026-07-16): rotate ~/.openclaw logs + prune unbounded ledgers.

    Three growth sinks with no retention anywhere: service logs under
    ~/.openclaw/logs (metis-command.log hit 80MB — launchd KeepAlive appends
    forever), the dispatch ledger (32MB, ~20KB/record with full model output
    inline, re-parsed by metis-status on every call), and per-lane session
    trajectory JSONLs (135MB/437 files). Daily, safe, in-place:
      - *.log over LOG_CAP -> tail-keep LOG_KEEP bytes (copytruncate-style; the
        launchd writers open O_APPEND so the next write lands at the new EOF)
      - dispatch-corrections.jsonl -> tail-keep LEDGER_KEEP records (the meter
        reads 24h; metis-status reads recent — months of inline model output
        serve nobody)
      - every per-session artifact under agents/*/sessions older than TRAJ_DAYS ->
        deleted (dedupe recovery only ever needs recent sessions); sessions.json and
        skills-prompts/ are preserved
    """
    base = os.path.expanduser("~/.openclaw")
    log_cap = int(os.environ.get("METIS_LOG_CAP_MB", "20")) * 1024 * 1024
    log_keep = int(os.environ.get("METIS_LOG_KEEP_MB", "5")) * 1024 * 1024
    ledger_keep = int(os.environ.get("METIS_DISPATCH_LEDGER_KEEP", "500"))
    traj_days = int(os.environ.get("METIS_TRAJECTORY_KEEP_DAYS", "30"))
    actions, freed = [], 0

    # 1. oversized service logs → tail-keep in place (r+b: read tail, rewrite, truncate)
    for f in sorted(glob.glob(os.path.join(base, "logs", "*.log"))):
        try:
            size = os.path.getsize(f)
        except OSError:
            continue
        if size <= log_cap:
            continue
        if apply:
            try:
                with open(f, "r+b") as fh:
                    fh.seek(size - log_keep)
                    tail = fh.read()
                    nl = tail.find(b"\n")  # start on a whole line
                    tail = tail[nl + 1:] if nl != -1 else tail
                    fh.seek(0)
                    fh.write(b"[rotated by self-heal #795]\n" + tail)
                    fh.truncate()
                freed += size - len(tail)
                actions.append(f"rotated {os.path.basename(f)}: {size >> 20}MB -> {len(tail) >> 20}MB")
            except OSError as e:
                actions.append(f"FAILED rotate {os.path.basename(f)}: {e}")
        else:
            actions.append(f"would rotate {os.path.basename(f)} ({size >> 20}MB > {log_cap >> 20}MB cap)")

    # 2. dispatch ledger → tail-keep newest records (atomic replace; appenders
    #    open-per-write so the worst race is one record during the swap second)
    ledger = os.path.join(base, "feedback", "dispatch-corrections.jsonl")
    routing_ledger = os.path.join(base, "feedback", "dispatch-routing.jsonl")
    routing_keep = int(os.environ.get("METIS_ROUTING_LEDGER_KEEP", "50000"))
    if os.path.exists(ledger):
        try:
            with open(ledger, "rb") as fh:
                lines = fh.readlines()
            if len(lines) > ledger_keep:
                if apply:
                    # Project the records about to be evicted into the routing ledger BEFORE
                    # dropping them (#4425), so the routing signal survives the eviction.
                    evicted = lines[:-ledger_keep]
                    slim_written = 0
                    try:
                        with open(routing_ledger, "a", encoding="utf-8") as rf:
                            for raw in evicted:
                                try:
                                    rec = json.loads(raw)
                                except Exception:
                                    continue
                                rf.write(json.dumps(_slim_routing_record(rec),
                                                    separators=(",", ":")) + "\n")
                                slim_written += 1
                    except OSError as e:
                        actions.append(f"FAILED routing projection: {e}")
                    tmp = ledger + ".rotate"
                    with open(tmp, "wb") as fh:
                        fh.writelines(lines[-ledger_keep:])
                    old = os.path.getsize(ledger)
                    os.replace(tmp, ledger)
                    freed += old - os.path.getsize(ledger)
                    actions.append(f"pruned dispatch ledger: {len(lines)} -> {ledger_keep} records"
                                   + (f" ({slim_written} projected to routing ledger)" if slim_written else ""))
                else:
                    actions.append(f"would prune dispatch ledger ({len(lines)} > {ledger_keep} records, "
                                   f"{len(lines) - ledger_keep} projected to the routing ledger)")
        except OSError as e:
            actions.append(f"FAILED ledger prune: {e}")

    # 2b. keep the routing projection bounded too -- it is slim, not free.
    if apply and os.path.exists(routing_ledger):
        try:
            with open(routing_ledger, "rb") as fh:
                rlines = fh.readlines()
            if len(rlines) > routing_keep:
                tmp = routing_ledger + ".rotate"
                with open(tmp, "wb") as fh:
                    fh.writelines(rlines[-routing_keep:])
                os.replace(tmp, routing_ledger)
                actions.append(f"trimmed routing ledger: {len(rlines)} -> {routing_keep} records")
        except OSError as e:
            actions.append(f"FAILED routing-ledger trim: {e}")

    # 3. stale session artifacts (#4397). This globbed "*.jsonl", which matched only 4,266 of
    #    the ~32,800 files actually living in these dirs: every ".archived-<ts>" copy, every
    #    ".trajectory-path.json" sidecar and every ".jsonl.codex-app-server.json.migrated" was
    #    invisible to it. So the prune ran daily, reported "deleted N trajectory files", and the
    #    dirs grew to 11GB anyway -- the success message is exactly what kept it unnoticed.
    #    Enumerate instead, and protect the two things that are not per-session artifacts:
    #    sessions.json (the live index read by queue-runner/self-heal/hook-session-init) and the
    #    skills-prompts/ subdir.
    cutoff = time.time() - traj_days * 86400
    session_keep = {"sessions.json"}
    stale = []
    for sdir in glob.glob(os.path.join(base, "agents", "*", "sessions")):
        try:
            names = os.listdir(sdir)
        except OSError:
            continue
        for name in names:
            if name in session_keep or name.startswith("."):
                continue
            f = os.path.join(sdir, name)
            try:
                if os.path.isfile(f) and os.path.getmtime(f) < cutoff:
                    stale.append(f)
            except OSError:
                continue
    if stale:
        if apply:
            n = 0
            for f in stale:
                try:
                    freed += os.path.getsize(f)
                    os.remove(f)
                    n += 1
                except OSError:
                    pass
            actions.append(f"deleted {n} session artifacts older than {traj_days}d")
        else:
            actions.append(f"would delete {len(stale)} session artifacts older than {traj_days}d")

    if not actions:
        return {"name": "log-rotation", "status": OK,
                "detail": f"logs <= {log_cap >> 20}MB, ledger <= {ledger_keep} recs, no stale trajectories",
                "actions": []}
    return {"name": "log-rotation",
            "status": HEALED if apply else NEEDS_HUMAN,
            "detail": f"{len(actions)} rotation action(s)" + (f", freed {freed >> 20}MB" if apply else ""),
            "actions": actions}


