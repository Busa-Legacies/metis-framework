def check_memory_pressure(apply):
    """Host memory pressure — critically low available RAM or a saturated swap file means
    the OS is about to jettison working sets (2026-07-15 <<MACHINE_2_ID>> incident: ~76MB free +
    swap 87% full at 34d uptime → WebKit tab reload-storm, found only by hand). Detection
    only (agent-tier): the remedy is quitting heavy non-load-bearing apps / rebooting, a
    human call — never an auto-kill. macOS keeps `Pages free` low by design (unused RAM is
    cache), so gating on raw free would false-WARN on a healthy host; we gate on *available*
    (free + inactive + speculative) plus swap saturation, which stays green when healthy and
    trips only under genuine pressure."""
    if sys.platform != "darwin":
        return {"name": "memory-pressure", "status": OK, "detail": "non-macOS host — skipped", "actions": []}
    MIN_AVAIL_MB, MAX_SWAP_PCT = 500, 85
    # available RAM from vm_stat (page size read from its own header — 16K on Apple Silicon)
    rc, vm = sh(["vm_stat"])
    if rc != 0 or "Pages free" not in vm:
        return {"name": "memory-pressure", "status": OK, "detail": f"vm_stat unavailable (rc={rc})", "actions": []}
    m = re.search(r"page size of (\d+) bytes", vm)
    pagesize = int(m.group(1)) if m else 4096
    def _pages(label):
        mm = re.search(rf"{re.escape(label)}:\s+(\d+)\.", vm)
        return int(mm.group(1)) if mm else 0
    avail_mb = (_pages("Pages free") + _pages("Pages inactive") + _pages("Pages speculative")) * pagesize // (1 << 20)
    # swap saturation from sysctl (the stronger thrash signal)
    swap_pct = None
    rc2, sw = sh(["sysctl", "-n", "vm.swapusage"])
    if rc2 == 0:
        tot = re.search(r"total\s*=\s*([\d.]+)M", sw)
        usd = re.search(r"used\s*=\s*([\d.]+)M", sw)
        if tot and usd and float(tot.group(1)) > 0:
            swap_pct = round(100 * float(usd.group(1)) / float(tot.group(1)))
    low_ram = avail_mb < MIN_AVAIL_MB
    high_swap = swap_pct is not None and swap_pct > MAX_SWAP_PCT
    swaptxt = f", swap {swap_pct}% used" if swap_pct is not None else ""
    if not (low_ram or high_swap):
        return {"name": "memory-pressure", "status": OK,
                "detail": f"available RAM {avail_mb}MB{swaptxt}", "actions": []}
    # name the top RSS consumers so the worklist line is actionable
    top = []
    rc3, ps = sh(["ps", "axo", "rss,comm"])
    if rc3 == 0:
        rows = []
        for line in ps.splitlines()[1:]:
            parts = line.strip().split(None, 1)
            if len(parts) == 2 and parts[0].isdigit():
                rows.append((int(parts[0]), parts[1]))
        rows.sort(reverse=True)
        top = [f"{comm.rsplit('/', 1)[-1]} {rss // 1024}MB" for rss, comm in rows[:5]]
    reasons = []
    if low_ram:
        reasons.append(f"available RAM {avail_mb}MB (< {MIN_AVAIL_MB}MB)")
    if high_swap:
        reasons.append(f"swap {swap_pct}% used (> {MAX_SWAP_PCT}%)")
    detail = "memory pressure: " + "; ".join(reasons) + (" — top RSS: " + ", ".join(top) if top else "")
    return {"name": "memory-pressure", "status": NEEDS_HUMAN, "escalation": AGENT, "detail": detail,
            "actions": ["quit the heaviest non-load-bearing apps (see top RSS above)",
                        "if chronic, reboot to clear a long-uptime leak (<<MACHINE_2_ID>> tripped this at 34d uptime)"]}


