# wakeWhen: the condition a `waiting` task self-triggers on (scripts/task_wake.py).
#   type=time  -> `at` is an ISO date/datetime; ready when now >= at.
#   type=check -> `cmd` is a shell command; ready when it exits 0 (data soak / CI / external).
